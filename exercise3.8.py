places = ["swis", "landon", "umroh", "jerman", "jepang", "switzerland"]

# Cetak daftar sesuai urutan asli
print(places)

# Cetak daftar berdasarkan urutan abjad
print(sorted(places))

# Cetak kembali daftar asli
print(places)

# Cetak daftar berdasarkan urutan abjad terbalik
print(sorted(places, reverse=True))

# Cetak kembali daftar asli
print(places)

# Membalik urutan daftar
places.reverse()
print(places)

# Membalik urutan kembali seperti semula
places.reverse()
print(places)

# Mengurutkan daftar berdasarkan abjad
places.sort()
print(places)

# Mengurutkan daftar berdasarkan abjad terbalik
places.sort(reverse=True)
print(places)