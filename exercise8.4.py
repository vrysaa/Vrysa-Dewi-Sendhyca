
def make_shirt(size="besar", message="I love Python"):
    print(f"Kaus berukuran {size} dengan tulisan '{message}'.")

# Kaus besar dengan pesan default
make_shirt()

# Kaus sedang dengan pesan default
make_shirt(size="sedang")

# Kaus dengan pesan berbeda
make_shirt(size="kecil", message="Belajar Python")